def login(browser, video_dir):
    login_ctx = browser.new_context(viewport={"width": 1440, "height": 1000})
    login_page = login_ctx.new_page()
    login_page.goto(f"{BASE_URL}/login", wait_until="networkidle")
    login_page.fill("input[name=email]", DEMO_EMAIL)
    login_page.fill("input[name=password]", DEMO_PASSWORD)
    login_page.click("button[type=submit]")
    try:
        login_page.wait_for_url(f"{BASE_URL}/dashboard", timeout=15000)
    except PWTimeoutError:
        raise RuntimeError(f"LOGIN FAILED — current URL: {login_page.url}")
    storage_state = login_ctx.storage_state()
    login_ctx.close()

    # service_workers="block" mirrors campaigns.py — the portal's sw.js
    # would otherwise intercept fetches ahead of Playwright's network layer.
    ctx = browser.new_context(
        viewport={"width": 1440, "height": 1000},
        storage_state=storage_state,
        record_video_dir=str(video_dir),
        record_video_size={"width": 1440, "height": 1000},
        service_workers="block",
    )
    ctx.add_init_script("localStorage.setItem('phixtra_tour_done', '1');")
    page = ctx.new_page()
    return page, ctx


def record(page, hold, mark, beat_ms):
    # --- b1_landing: land on the dashboard, default period (this month) ---
    page.goto(f"{BASE_URL}/dashboard", wait_until="networkidle", timeout=20000)
    hold("b1_landing")

    # --- b1_kpis: camera drifts across the 4 KPI cards ---
    page.locator("#dashSalesOverview").scroll_into_view_if_needed()
    hold("b1_kpis", motion=[
        "#dashSalesOverview .kpi-card:nth-child(1)",
        "#dashSalesOverview .kpi-card:nth-child(2)",
        "#dashSalesOverview .kpi-card:nth-child(3)",
        "#dashSalesOverview .kpi-card:nth-child(4)",
    ])

    # --- b1_period_open: highlight the date-range picker, no action yet ---
    hold("b1_period_open", motion=["select[name=period]"])

    # --- b1_period_after: actually switch period (real reload), hold on
    #     the recalculated KPI row so the change is visibly proven, not
    #     just claimed in narration ---
    page.select_option("select[name=period]", value="this_quarter")
    page.wait_for_load_state("networkidle")
    page.locator("#dashSalesOverview").scroll_into_view_if_needed()
    hold("b1_period_after", motion=[
        "#dashSalesOverview .kpi-card:nth-child(1)",
        "#dashSalesOverview .kpi-card:nth-child(2)",
    ])

    # --- b2_pipeline: Sales Pipeline snapshot ---
    page.locator("#dashPipelineCard").scroll_into_view_if_needed()
    hold("b2_pipeline")

    # --- b2_stage: highlight one stage row — never click, stays off the
    #     real Pipeline Board (that's its own, separate video) ---
    hold("b2_stage", motion=["#dashPipelineCard .frow"])

    # --- b2_sources: Lead Sources card ---
    page.locator("#dashSourcesCard").scroll_into_view_if_needed()
    hold("b2_sources")

    # --- b3_channel: Channel Activity, real WhatsApp card ---
    page.locator("#dashChannelActivity").scroll_into_view_if_needed()
    hold("b3_channel", motion=["#dashChannelActivity > div:nth-child(1)"])

    # --- b3_locked: the two honest "coming soon" cards ---
    hold("b3_locked", motion=[
        "#dashChannelActivity > div:nth-child(2)",
        "#dashChannelActivity > div:nth-child(3)",
    ])

    # --- b4_campaign: Campaign Performance funnel ---
    page.locator("#dashCampaignCard").scroll_into_view_if_needed()
    hold("b4_campaign")

    # --- b4_revenue: the revenue line + per-campaign breakdown ---
    page.locator("#dashCampaignCard .camp-row").first.scroll_into_view_if_needed()
    hold("b4_revenue")

