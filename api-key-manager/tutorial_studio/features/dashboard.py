    page.locator("#dashActivityCard").scroll_into_view_if_needed()
    hold("b5_activity")

    # --- b6_close: bookend back on the KPI row for a clean closing shot ---
    page.locator("#dashSalesOverview").scroll_into_view_if_needed()
    hold("b6_close")
